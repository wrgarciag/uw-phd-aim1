function [lhs, rhs] = dynamic_resid(y, x, params, steady_state)
T = NaN(7, 1);
lhs = NaN(5, 1);
rhs = NaN(5, 1);
T(1) = y(7)^params(2);
T(2) = x(1)^(1-params(2));
T(3) = y(6)^(-1);
T(4) = params(1)*y(11)^(-1);
T(5) = params(2)*y(7)^(params(2)-1);
T(6) = y(15)^(1-params(2));
T(7) = 1+T(5)*T(6)-params(3);
lhs(1) = y(8);
rhs(1) = T(1)*T(2);
lhs(2) = y(6)+y(9);
rhs(2) = y(8);
lhs(3) = y(9)+(1-params(3))*y(2);
rhs(3) = y(7)*(1+x(3))*(1+x(2));
lhs(4) = (1+x(3))*T(3);
rhs(4) = T(4)*T(7);
lhs(5) = y(10);
rhs(5) = x(1);
end
