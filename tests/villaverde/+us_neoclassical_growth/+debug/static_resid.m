function [lhs, rhs] = static_resid(y, x, params)
T = NaN(5, 1);
lhs = NaN(5, 1);
rhs = NaN(5, 1);
T(1) = x(1)^(1-params(2));
T(2) = y(1)^(-1);
T(3) = params(2)*y(2)^(params(2)-1);
T(4) = y(5)^(1-params(2));
T(5) = 1+T(3)*T(4)-params(3);
lhs(1) = y(3);
rhs(1) = y(2)^params(2)*T(1);
lhs(2) = y(1)+y(4);
rhs(2) = y(3);
lhs(3) = y(4)+y(2)*(1-params(3));
rhs(3) = y(2)*(1+x(3))*(1+x(2));
lhs(4) = (1+x(3))*T(2);
rhs(4) = T(2)*params(1)*T(5);
lhs(5) = y(5);
rhs(5) = x(1);
end
